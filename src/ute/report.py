"""Regenerate docs/results.md and the RESULTS block of the README from artifacts/metrics.json.

Every number in those files comes from here, so they never drift from what was measured.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import pandas as pd

from ute import config

LABELS = {
    "random": "Random targeting",
    "response": "Response model (treated-group propensity)",
    "s_learner": "S-learner",
    "t_learner": "T-learner",
    "x_learner": "X-learner",
    "transformed_outcome": "Transformed outcome",
}
PER = 100_000


def _ci(m: dict, scale: float = 1.0, fmt: str = "{:.3f}") -> str:
    return (
        f"{fmt.format(m['value'] * scale)} "
        f"[{fmt.format(m['ci_low'] * scale)}, {fmt.format(m['ci_high'] * scale)}]"
    )


def _pp(m: dict) -> str:
    return _ci(m, 100, "{:.3f}")


def model_table(info: dict) -> str:
    rows = [
        "| Model | Qini coef. (test) | AUUC (test) | uplift@10% (pp) | uplift@20% (pp) "
        "| uplift@30% (pp) | Qini (valid) |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, m in info["models"].items():
        star = " **(production)**" if info.get("production_model") == name else ""
        rows.append(
            f"| {LABELS.get(name, name)}{star} | {_ci(m['qini'])} | {_ci(m['auuc'])} "
            f"| {_pp(m['uplift@10'])} | {_pp(m['uplift@20'])} | {_pp(m['uplift@30'])} "
            f"| {m['valid_qini']:.3f} |"
        )
    return "\n".join(rows)


def headline(summary: dict) -> str:
    meta = summary["meta"]
    conv = summary["outcomes"]["conversion"]
    prod = conv.get("production_model")
    lines = [
        f"Criteo Uplift v2.1, **{meta['rows']:,} rows**"
        + (f" (sample {meta['sample_frac']:.0%})" if meta.get("sample_frac") else "")
        + f"; test split {meta['split']['test']:,} rows; treatment share "
        f"{meta['treatment_share']:.1%}; {meta['n_boot']} Poisson-bootstrap replicates "
        "(95% intervals in brackets). Outcome: **conversion**.",
        "",
        "| | Value |",
        "|---|---|",
        f"| Conversion rate, treated / control | {conv['base_rate_treated']:.4%} / "
        f"{conv['base_rate_control']:.4%} |",
        f"| Average treatment effect (= expected uplift of random targeting) "
        f"| {conv['ate'] * 100:.4f} pp |",
    ]
    if prod:
        m = conv["models"][prod]
        u20 = m["uplift@20"]["value"]
        lines += [
            f"| Production model (best **validation** Qini) | {LABELS[prod]} |",
            f"| Qini coefficient, test | {_ci(m['qini'])} |",
            f"| uplift@20%, test | {_pp(m['uplift@20'])} pp |",
            f"| Incremental conversions per {PER:,} customers, top 20% targeted "
            f"| **{u20 * PER * 0.2:.0f}** vs {conv['ate'] * PER * 0.2:.0f} for random 20% "
            f"(**{u20 / conv['ate']:.1f}x**) |",
        ]
        resp = conv["models"].get("response")
        if resp:
            lines.append(
                f"| Same budget, response model | {resp['uplift@20']['value'] * PER * 0.2:.0f} "
                f"(Qini {resp['qini']['value']:.3f}) |"
            )
    leak = summary.get("leakage")
    if leak:
        clean = leak["clean"]["response_model_auc_treated"]
        leaky = leak["leaky"]["response_model_auc_treated"]
        lines.append(
            "| Leakage study: response-model ROC AUC, clean vs with `exposure`+`visit` "
            f"| {clean:.3f} vs **{leaky:.3f}** |"
        )
    return "\n".join(lines)


def results_md(summary: dict, artifacts_dir: Path = config.ARTIFACTS_DIR) -> str:
    meta = summary["meta"]
    out = [
        "# Results",
        "",
        "Generated by `ute report` from `artifacts/metrics.json` "
        f"(run {meta['created_at']}, {meta['total_seconds']:.0f} s end to end). "
        "Do not edit by hand.",
        "",
        headline(summary),
        "",
        "Metric definitions are in [`src/ute/metrics.py`](../src/ute/metrics.py). Qini coefficient "
        "and AUUC are normalised: 1 is a perfect ranking, 0 is random. uplift@k is the treated "
        "minus control conversion rate among the top k of the ranking, in percentage points.",
        "",
    ]
    for outcome, info in summary["outcomes"].items():
        tag = "primary" if outcome == "conversion" else "secondary"
        out += [
            f"## Outcome: {outcome} ({tag})",
            "",
            f"Base rate treated {info['base_rate_treated']:.4%}, control "
            f"{info['base_rate_control']:.4%}, ATE {info['ate'] * 100:.4f} pp.",
            "",
            model_table(info),
            "",
            "Fit time and trees (after early stopping on the validation split):",
            "",
            "| Model | Fit seconds | Trees |",
            "|---|---|---|",
        ]
        for name, m in info["models"].items():
            trees = ", ".join(f"{k.rstrip('_')}={v}" for k, v in m["n_trees"].items()) or "-"
            out.append(f"| {LABELS.get(name, name)} | {m['fit_seconds']:.0f} | {trees} |")
        out.append("")

    dec = artifacts_dir / "deciles.csv"
    if dec.exists():
        d = pd.read_csv(dec)
        d = d[d["outcome"] == "conversion"]
        if len(d):
            out += [
                f"## Deciles of the production model ({LABELS[d['model'].iloc[0]]}, test)",
                "",
                "| Decile | Customers | CR treated | CR control | Observed uplift (pp) |",
                "|---|---|---|---|---|",
            ]
            for r in d.itertuples():
                out.append(
                    f"| {r.decile} | {r.n:,} | {r.cr_treated:.4%} | {r.cr_control:.4%} "
                    f"| {r.uplift * 100:.4f} |"
                )
            out.append("")

    leak = summary.get("leakage")
    if leak:
        c, lk = leak["clean"], leak["leaky"]
        out += [
            "## Leakage study",
            "",
            f"T-learner and response model refit with the post-treatment columns "
            f"{', '.join('`' + x + '`' for x in leak['post_treatment_columns'])} added to f0-f11.",
            "",
            "| | Clean (f0-f11) | Leaky (+ post-treatment) |",
            "|---|---|---|",
            f"| Response model ROC AUC on treated test rows | "
            f"{c['response_model_auc_treated']:.3f} | {lk['response_model_auc_treated']:.3f} |",
            f"| T-learner Qini coefficient | {_ci(c['t_learner']['qini'])} | "
            f"{_ci(lk['t_learner']['qini'])} |",
            f"| T-learner AUUC | {_ci(c['t_learner']['auuc'])} | {_ci(lk['t_learner']['auuc'])} |",
            f"| T-learner uplift@20% (pp) | {_pp(c['t_learner']['uplift@20'])} | "
            f"{_pp(lk['t_learner']['uplift@20'])} |",
            "",
            "The leaky columns are only known after the campaign ran, so the leaky model cannot "
            "be used to choose who receives the voucher. See the README for the reasoning.",
            "",
        ]

    dr = summary.get("drift")
    if dr:
        out += [
            "## Drift check (PSI)",
            "",
            f"Reference: {dr['reference']}; current: {dr['current']}. The last two columns score "
            f"a **simulated** batch ({dr['simulated_shift']}) to show what an alert looks like.",
            "",
            "| Feature | PSI test vs train | Status | PSI simulated shift | Status |",
            "|---|---|---|---|---|",
        ]
        for r in dr["features"]:
            out.append(
                f"| {r['feature']} | {r['psi']:.4f} | {r['status']} | "
                f"{r['psi_simulated_shift']:.4f} | {r['status_simulated_shift']} |"
            )
        out.append("")
    return "\n".join(out)


def update_readme(summary: dict, readme: Path) -> None:
    text = readme.read_text(encoding="utf-8")
    block = f"<!-- RESULTS:START -->\n{headline(summary)}\n<!-- RESULTS:END -->"
    new, n = re.subn(
        r"<!-- RESULTS:START -->.*?<!-- RESULTS:END -->", lambda _: block, text, flags=re.S
    )
    if n != 1:
        raise ValueError("README is missing the RESULTS markers")
    readme.write_text(new, encoding="utf-8")


def main(
    metrics_path: Path = config.ARTIFACTS_DIR / "metrics.json",
    docs_dir: Path = config.DOCS_DIR,
    readme: Path = config.ROOT / "README.md",
) -> None:
    summary = json.loads(metrics_path.read_text())
    docs_dir.mkdir(parents=True, exist_ok=True)
    (docs_dir / "results.md").write_text(results_md(summary, metrics_path.parent), encoding="utf-8")
    if readme.exists():
        update_readme(summary, readme)
